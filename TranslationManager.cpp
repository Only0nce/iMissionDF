TranslationManager::TranslationManager(QObject *parent)
    : QObject(parent)
{
    QSettings settings;
    QString initial = settings.value(QStringLiteral("ui/language"),
                                     QStringLiteral("en")).toString();

    // R1.7.3B:
    // Allow deterministic target-side testing without relying on the QML button.
    // Example:
    //   ISCAN_LANGUAGE=th /opt/iScanMR10/bin/iScanMR10
    const QString envLanguage =
        QString::fromLocal8Bit(qgetenv("ISCAN_LANGUAGE")).trimmed().toLower();

    if (envLanguage == QStringLiteral("en") ||
        envLanguage == QStringLiteral("th") ||
        envLanguage == QStringLiteral("english") ||
        envLanguage == QStringLiteral("thai")) {
        qInfo() << "[I18N] ISCAN_LANGUAGE override =" << envLanguage;
        initial = envLanguage;
    }

    m_language = QStringLiteral("en");
    setLanguage(initial);
}

QString TranslationManager::language() const
{
    return m_language;
}

bool TranslationManager::setLanguage(const QString &languageCode)
{
    QString code = languageCode.trimmed().toLower();

    if (code == QStringLiteral("thai"))
        code = QStringLiteral("th");
    if (code == QStringLiteral("english"))
        code = QStringLiteral("en");

    if (code != QStringLiteral("en") && code != QStringLiteral("th")) {
        qWarning() << "[I18N] unsupported language:" << languageCode;
        return false;
    }

    qApp->removeTranslator(&m_translator);

    bool translatorOk = true;
    if (code != QStringLiteral("en"))
        translatorOk = loadQtTranslator(code);

    m_language = code;

    QSettings settings;
    settings.setValue(QStringLiteral("ui/language"), m_language);

    emit languageChanged();

    qInfo() << "[I18N] language=" << m_language
            << "qtTranslatorOk=" << translatorOk
            << "fallbackGlossary=true";

    return translatorOk;
}

bool TranslationManager::loadQtTranslator(const QString &languageCode)
{
    const QString fileName = QStringLiteral("iScanMR10_%1.qm").arg(languageCode);

    const QStringList candidates = {
        QStringLiteral(":/translations/") + fileName,
        QCoreApplication::applicationDirPath() + QStringLiteral("/translations/") + fileName,
        QCoreApplication::applicationDirPath() + QStringLiteral("/../translations/") + fileName,
        QDir::currentPath() + QStringLiteral("/translations/") + fileName
    };

    for (const QString &path : candidates) {
        if (m_translator.load(path)) {
            qApp->installTranslator(&m_translator);
            qInfo() << "[I18N] loaded Qt translator:" << path;
            return true;
        }
    }

    qWarning() << "[I18N] Qt .qm translator not found for" << languageCode
               << "using glossary fallback";
    return false;
}

QString TranslationManager::text(const QString &source) const
{
    if (m_language != QStringLiteral("th"))
        return source;

    const QString key = source.trimmed();
    const auto &map = thaiGlossary();

    auto it = map.constFind(key);
    if (it != map.constEnd())
        return it.value();

    return source;
}

